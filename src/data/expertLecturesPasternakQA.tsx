import { useState, ReactNode } from 'react';
import { ChevronDown, ChevronRight } from 'lucide-react';

type QAItem = {
  q: string;
  summary: ReactNode;
  explanation: string;
};

type QAGroup = {
  chapterTitle: string;
  items: QAItem[];
};

// Render plain text with markdown-like **bold** support and paragraph splitting.
function renderExplanation(text: string): ReactNode {
  const lines = text.split('\n');
  const nodes: ReactNode[] = [];
  let buffer: string[] = [];
  let listBuffer: string[] = [];

  const flushParas = () => {
    if (buffer.length > 0) {
      const paragraph = buffer.join(' ').trim();
      if (paragraph) {
        nodes.push(
          <p key={`p-${nodes.length}`} className="mb-3 leading-relaxed">
            {renderInlineBold(paragraph)}
          </p>
        );
      }
      buffer = [];
    }
  };

  const flushList = () => {
    if (listBuffer.length > 0) {
      nodes.push(
        <ul key={`ul-${nodes.length}`} className="list-disc pl-6 mb-3 space-y-1">
          {listBuffer.map((item, idx) => (
            <li key={idx} className="leading-relaxed">{renderInlineBold(item)}</li>
          ))}
        </ul>
      );
      listBuffer = [];
    }
  };

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) {
      flushParas();
      flushList();
      continue;
    }
    // Detect list-style lines (simple heuristic)
    const isListLine =
      /^[・●\-]/.test(line) ||
      (buffer.length === 0 && /^[A-Za-z]+[-*]/.test(line));
    if (isListLine) {
      flushParas();
      listBuffer.push(line.replace(/^[・●\-]\s*/, ''));
      continue;
    }
    // If buffer is empty and line looks like a continuation short fragment, start new para
    buffer.push(line);
  }
  flushParas();
  flushList();
  return <>{nodes}</>;
}

function renderInlineBold(text: string): ReactNode {
  const parts = text.split(/\*\*(.+?)\*\*/g);
  return parts.map((part, i) =>
    i % 2 === 1 ? (
      <strong key={i} className="text-indigo-800">{part}</strong>
    ) : (
      <span key={i}>{part}</span>
    )
  );
}

function QAEntry({
  item,
  isOpen,
  onToggle,
}: {
  item: QAItem;
  isOpen: boolean;
  onToggle: () => void;
}) {
  return (
    <div className="border border-gray-200 rounded-lg overflow-hidden bg-white">
      <button
        onClick={onToggle}
        className={`w-full text-left px-4 py-3 flex items-start justify-between gap-3 transition-colors ${
          isOpen ? 'bg-indigo-50' : 'bg-white hover:bg-gray-50'
        }`}
      >
        <span className={`font-medium text-sm md:text-base leading-snug ${isOpen ? 'text-indigo-900' : 'text-gray-900'}`}>
          {item.q}
        </span>
        <span className="shrink-0 mt-0.5 text-indigo-600">
          {isOpen ? <ChevronDown className="w-5 h-5" /> : <ChevronRight className="w-5 h-5" />}
        </span>
      </button>
      {isOpen && (
        <div className="px-4 py-5 border-t border-gray-200 space-y-6 bg-white">
          <div>
            <div className="inline-block px-3 py-1 rounded-full bg-emerald-100 text-emerald-800 text-xs font-bold mb-3">
              要約（やさしい解説）
            </div>
            <div className="text-sm text-gray-800 leading-relaxed">
              {item.summary}
            </div>
          </div>
          <div>
            <div className="inline-block px-3 py-1 rounded-full bg-indigo-100 text-indigo-800 text-xs font-bold mb-3">
              解説（講演内容）
            </div>
            <div className="text-sm text-gray-800">
              {renderExplanation(item.explanation)}
            </div>
          </div>
        </div>
      )}
    </div>
  );
}

function QAAccordion({ groups }: { groups: QAGroup[] }) {
  const [openKey, setOpenKey] = useState<string | null>(null);
  return (
    <div className="space-y-8">
      {groups.map((group, gIdx) => (
        <div key={gIdx}>
          <h4 className="text-lg font-bold text-indigo-800 mb-4 bg-indigo-50 p-2 rounded">
            {group.chapterTitle}
          </h4>
          <div className="space-y-2">
            {group.items.map((item, iIdx) => {
              const key = `${gIdx}-${iIdx}`;
              return (
                <div key={key}>
                  <QAEntry
                    item={item}
                    isOpen={openKey === key}
                    onToggle={() => setOpenKey(openKey === key ? null : key)}
                  />
                </div>
              );
            })}
          </div>
        </div>
      ))}
    </div>
  );
}

